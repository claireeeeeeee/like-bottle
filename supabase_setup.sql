create extension if not exists pgcrypto;

create table if not exists public.bottles (
  id bigint generated by default as identity primary key,
  name text not null,
  category text not null default '',
  sort_order integer not null default 0,
  created_at timestamptz not null default now()
);

create table if not exists public.submissions (
  id bigint generated by default as identity primary key,
  player_name text not null,
  answers jsonb not null,
  created_at timestamptz not null default now()
);

create table if not exists public.app_config (
  key text primary key,
  value text not null
);

insert into public.app_config(key, value)
values ('editor_code_hash', crypt('kisskissme', gen_salt('bf')))
on conflict (key) do update set value = excluded.value;

insert into public.bottles(name, sort_order)
select v.name, v.sort_order
from (values ('人物 A',1),('人物 B',2),('人物 C',3),('人物 D',4)) as v(name,sort_order)
where not exists (select 1 from public.bottles);

alter table public.bottles enable row level security;
alter table public.submissions enable row level security;
alter table public.app_config enable row level security;

drop policy if exists "public can read bottles" on public.bottles;
create policy "public can read bottles" on public.bottles for select to anon, authenticated using (true);

drop policy if exists "public can submit" on public.submissions;
create policy "public can submit" on public.submissions for insert to anon, authenticated
with check (char_length(player_name) between 1 and 80 and jsonb_typeof(answers)='array');

create or replace function public.check_editor_code(p_code text)
returns boolean language sql security definer set search_path=public as $$
  select exists(select 1 from public.app_config where key='editor_code_hash' and value=crypt(p_code,value));
$$;
revoke all on function public.check_editor_code(text) from public;
grant execute on function public.check_editor_code(text) to anon, authenticated;

create or replace function public.editor_get_bottles(p_code text)
returns jsonb language plpgsql security definer set search_path=public as $$
begin
  if not public.check_editor_code(p_code) then return jsonb_build_object('ok',false); end if;
  return jsonb_build_object('ok',true,'bottles',coalesce((select jsonb_agg(jsonb_build_object('id',id,'name',name,'category',category,'sort_order',sort_order) order by sort_order,id) from public.bottles),'[]'::jsonb));
end;$$;
revoke all on function public.editor_get_bottles(text) from public;
grant execute on function public.editor_get_bottles(text) to anon, authenticated;

create or replace function public.editor_replace_bottles(p_code text,p_names text[],p_categories text[])
returns jsonb language plpgsql security definer set search_path=public as $$
begin
  if not public.check_editor_code(p_code) then return jsonb_build_object('ok',false); end if;
  if not exists(select 1 from unnest(p_names) x where trim(x)<>'') then raise exception '至少需要一个瓶子'; end if;
  delete from public.bottles where true;
  insert into public.bottles(name,category,sort_order)
  select trim(n),coalesce(trim(c),''),ord::int from unnest(p_names,p_categories) with ordinality as t(n,c,ord) where trim(n)<>'';
  return jsonb_build_object('ok',true,'bottles',(select jsonb_agg(jsonb_build_object('id',id,'name',name,'category',category,'sort_order',sort_order) order by sort_order,id) from public.bottles));
end;$$;
revoke all on function public.editor_replace_bottles(text,text[],text[]) from public;
grant execute on function public.editor_replace_bottles(text,text[],text[]) to anon, authenticated;

create or replace function public.editor_get_submissions(p_code text,p_limit integer default 100)
returns jsonb language plpgsql security definer set search_path=public as $$
begin
  if not public.check_editor_code(p_code) then return jsonb_build_object('ok',false); end if;
  return jsonb_build_object('ok',true,'submissions',coalesce((select jsonb_agg(jsonb_build_object('id',s.id,'player_name',s.player_name,'answers',s.answers,'created_at',s.created_at) order by s.created_at desc) from (select * from public.submissions order by created_at desc limit greatest(1,least(coalesce(p_limit,100),500))) s),'[]'::jsonb));
end;$$;
revoke all on function public.editor_get_submissions(text,integer) from public;
grant execute on function public.editor_get_submissions(text,integer) to anon, authenticated;
